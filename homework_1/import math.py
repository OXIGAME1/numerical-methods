import math

def rel_err(x, x1):
    # то же, что в задании: abs(x - x1) / abs(x1)
    if x1 == 0:
        return float('inf')
    return abs(x - x1) / abs(x1)

def show(name, x, x1):
    print(f"{name}: абс={abs(x-x1):.6g}  отн={rel_err(x,x1)*100:.4g}%")


