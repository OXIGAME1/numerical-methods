getcontext().prec = 50           # 50 значащих цифр для эталона
D = Decimal                      # D(0.1) — ТОЧНОЕ значение того float, что лежит в памяти

EULER_GAMMA = D("0.57721566490153286060651209008240243104215933593992")


# ---------------------------------------------------------------------
# Вспомогательные функции
# ---------------------------------------------------------------------
def header(title):
    print("\n" + "=" * 78)
    print(title)
    print("=" * 78)


def rel_err(approx, exact):
    """Относительная ошибка |approx - exact| / |exact|, exact — Decimal."""
    return float(abs(D(approx) - exact) / abs(exact))


def table(head, rows):
    """Печать таблицы: head — список заголовков, rows — список списков строк."""
    widths = [max(len(str(h)), *(len(str(r[i])) for r in rows)) for i, h in enumerate(head)]
    line = " | ".join(str(h).ljust(w) for h, w in zip(head, widths))
    print(line)
    print("-" * len(line))
    for r in rows:
        print(" | ".join(str(c).ljust(w) for c, w in zip(r, widths)))


def slope(xs, ys):
    """Наклон прямой в log-log координатах (показатель степени)."""
    return np.polyfit(np.log10(xs), np.log10(ys), 1)[0]


def fmt(v):
    return f"{v:.3e}"


# Эталоны через decimal ------------------------------------------------
def ref_one_minus_cos_over_x2(x):
    """(1 - cos x)/x^2 = 1/2! - x^2/4! + x^4/6! - ...  (ряд, без вычитания близких чисел)"""
    x2 = D(x) ** 2
    term, total, k = D(1) / 2, D(0), 0
    while abs(term) > D(10) ** -60:
        total += term
        k += 1
        term = -term * x2 / ((2 * k + 1) * (2 * k + 2))
    return total


def ref_sqrt_diff(x):
    x = D(x)
    return (x + 1).sqrt() - x.sqrt()


def ref_harmonic(n):
    """H_n через асимптотику Эйлера–Маклорена; при n >= 1e5 точность ~1e-35."""
    n = D(n)
    return (n.ln() + EULER_GAMMA + 1 / (2 * n) - 1 / (12 * n**2)
            + 1 / (120 * n**4) - 1 / (252 * n**6))


