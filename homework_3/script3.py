# #####################################################################
# ЗАДАЧА 5. Квадратное уравнение — классика
# Условие: меньший корень при a=1, c=1, b = 1e4, 1e8, 1e12: плохая и хорошая формулы
# #####################################################################
def task5():
    header("Задача 5. Квадратное уравнение x^2 + b x + 1 = 0, меньший по модулю корень")
    a, c = 1.0, 1.0
    rows = []
    for b in [1e4, 1e8, 1e12]:
        sq = math.sqrt(b * b - 4 * a * c)
        bad = (-b + sq) / (2 * a)
        good = 2 * c / (-b - sq)
        Db = D(b)
        ref = 2 * D(c) / (-Db - (Db * Db - 4).sqrt())
        rows.append([f"{b:.0e}", f"{float(ref):.15e}", f"{bad:.6e}", f"{good:.15e}",
                     fmt(rel_err(bad, ref)), fmt(rel_err(good, ref))])
    table(["b", "эталон", "плохо", "хорошо", "ошибка плохого", "ошибка хорошего"], rows)
    print("""
«Плохая» формула вычитает почти равные числа: -b + sqrt(b^2 - 4) ≈ 0. Уже при b = 1e4
теряется половина знаков (~1e-9), при b = 1e8 ошибка уже ~25% (катастрофа),
при b = 1e12 b^2 - 4 == b^2 в float и корень получается ровно 0 (ошибка 100%).
«Хорошая» формула (через теорему Виета x1·x2 = c/a) вычитания близких чисел не делает:
ошибка ~1e-16 при любом b.
Вывод: катастрофически плохой способ начинает ошибаться при b ~ 1e8 = 1/sqrt(eps).""")


# #####################################################################
# ЗАДАЧА 6. (1 - cos x) при малых x
# Условие: (1 - cos x)/x^2 в лоб vs 2·sin^2(x/2)/x^2, x = 1e-2..1e-10, log-log график
# #####################################################################
def task6():
    header("Задача 6. (1 - cos x) / x^2 при малых x")
    bad = lambda x: (1 - math.cos(x)) / x**2
    good = lambda x: 2 * math.sin(x / 2) ** 2 / x**2

    xs = [1e-2, 1e-4, 1e-6, 1e-8, 1e-10]
    rows, eb, eg = [], [], []
    for x in xs:
        ref = ref_one_minus_cos_over_x2(x)
        e1, e2 = rel_err(bad(x), ref), rel_err(good(x), ref)
        eb.append(max(e1, 1e-18)); eg.append(max(e2, 1e-18))
        rows.append([f"{x:.0e}", f"{bad(x):.15e}", f"{good(x):.15e}", fmt(e1), fmt(e2)])
    table(["x", "плохо", "хорошо", "ошибка плохого", "ошибка хорошего"], rows)

    # Поиск, где ошибка плохого способа впервые > 1% (частая сетка)
    grid = np.logspace(-2, -10, 400)
    first = next(x for x in grid if rel_err(bad(float(x)), ref_one_minus_cos_over_x2(float(x))) > 0.01)
    print(f"\nОшибка «плохого» способа впервые превышает 1% при x ≈ {first:.2e}")

    plt.figure(figsize=(6, 4))
    plt.loglog(xs, eb, "o-", label="(1 - cos x)/x²  (плохо)")
    plt.loglog(xs, eg, "s-", label="2 sin²(x/2)/x²  (хорошо)")
    plt.axhline(0.01, color="r", ls=":", label="1%")
    plt.gca().invert_xaxis()
    plt.xlabel("x"); plt.ylabel("относительная ошибка"); plt.title("Задача 6")
    plt.legend(); plt.grid(True, which="both", alpha=.3); plt.tight_layout()
    plt.savefig("task6_cos.png", dpi=120); plt.close()
    print("График: task6_cos.png (нулевые ошибки нарисованы на уровне 1e-18)")
    print("""
При малых x cos x ≈ 1, и 1 - cos x — вычитание почти равных чисел: ошибка ~ eps/x^2.
При x <= 1e-8 cos x == 1.0 в float, и «плохой» способ выдаёт 0 вместо 0.5.
Тождество 2 sin^2(x/2) убирает вычитание — ошибка ~1e-16 для всех x.
Правило: если в формуле вычитаются две величины, которые при нужных x почти равны
(1 - cos x, sin a - sin b, cos a - cos b, ...), ищем тождество, превращающее разность
в произведение/частное.""")


# #####################################################################
# ЗАДАЧА 7. sqrt(x+1) - sqrt(x) при больших x
# Условие: в лоб vs 1/(sqrt(x+1) + sqrt(x)), x = 1e4..1e16, показатель роста ошибки
# #####################################################################
def task7():
    header("Задача 7. sqrt(x+1) - sqrt(x) при больших x")
    bad = lambda x: math.sqrt(x + 1) - math.sqrt(x)
    good = lambda x: 1 / (math.sqrt(x + 1) + math.sqrt(x))
    xs = [1e4, 1e8, 1e12, 1e14, 1e16]
    rows, eb = [], []
    for x in xs:
        ref = ref_sqrt_diff(x)
        e1, e2 = rel_err(bad(x), ref), rel_err(good(x), ref)
        eb.append(e1)
        rows.append([f"{x:.0e}", f"{bad(x):.10e}", f"{good(x):.10e}", fmt(e1), fmt(e2)])
    table(["x", "плохо", "хорошо", "ошибка плохого", "ошибка хорошего"], rows)
    k = slope(xs[:-1], eb[:-1])
    print(f"\nОценка показателя степени (по x = 1e4..1e14): ошибка ~ x^{k:.2f}")
    print("""
Ошибка «плохого» способа растёт примерно как x^1 (теория: eps · x, см. задачу 12):
sqrt(x+1) и sqrt(x) совпадают почти во всех знаках, и разность «съедает» их.
При x = 1e16 вообще x + 1 == x в float, результат 0, ошибка 100%.
«Хороший» способ (умножили и поделили на сопряжённое) разности не содержит —
ошибка ~1e-16 на всём диапазоне.""")


