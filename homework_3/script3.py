# #####################################################################
# ЗАДАЧА 1. Число обусловленности вручную
# Условие: cond = |x·f'(x)/f(x)| для sqrt(x), ln x, x-1, sin x; упорядочить по опасности
# #####################################################################
def task1():
    header("Задача 1. Число обусловленности вручную: cond = |x f'(x) / f(x)|")
    cases = [
        ("sqrt(x)", 1e-8,        lambda x: math.sqrt(x), lambda x: 0.5 / math.sqrt(x), "1/2 (всегда)"),
        ("ln(x)",   1.001,       math.log,               lambda x: 1 / x,              "1/ln x"),
        ("x - 1",   1.000001,    lambda x: x - 1,        lambda x: 1.0,                "x/(x-1)"),
        ("sin(x)",  math.pi / 2, math.sin,               math.cos,                     "x·ctg x"),
    ]
    rows, results = [], []
    for name, x, f, df, formula in cases:
        cond = abs(x * df(x) / f(x))
        verdict = "хорошо" if cond < 10 else ("плохо" if cond > 1e3 else "умеренно/плохо")
        rows.append([name, x, formula, fmt(cond), verdict])
        results.append((cond, name))
    table(["f(x)", "x", "формула cond", "cond", "обусловленность"], rows)
    print("\nПо возрастанию cond:", " < ".join(n for _, n in sorted(results)))
    print("""
Для sin при x = pi/2 cond = 0 (cos(pi/2) = 0; в float получается ~1e-16) — у максимума
функция «плоская», малое изменение x почти не меняет sin x.
Вывод: самая опасная задача — x - 1 при x ≈ 1 (cond ≈ 1e6): относительная ошибка
входа усиливается в миллион раз, т.к. результат — разность почти равных чисел.
ln x около 1 тоже плохо обусловлен (cond ≈ 1000) по той же причине: ln x ≈ x - 1.""")


# #####################################################################
# ЗАДАЧА 2. Вычитание близких чисел как плохая обусловленность
# Условие: f(a,b) = a - b, a = 1+1e-8, b = 1, δa = 1e-9; сравнить с предсказанием по cond
# #####################################################################
def task2():
    header("Задача 2. Вычитание близких чисел как плохая обусловленность")
    print("""Аналитически: f(a,b) = a - b, df/da = 1, df/db = -1.
  cond_a = |a · 1 / (a - b)| = |a| / |a - b|,   cond_b = |b| / |a - b|.
  При a ≈ b знаменатель ~0, оба числа обусловленности огромны.""")
    a, b, da = 1 + 1e-8, 1.0, 1e-9
    f0 = a - b
    f1 = (a + da) - b
    cond_a = abs(a / (a - b))
    rel_in = da / a
    rel_out_pred = cond_a * rel_in
    rel_out_fact = abs(f1 - f0) / abs(f0)
    print(f"\na = 1 + 1e-8, b = 1, δa = 1e-9")
    print(f"cond_a                          = {cond_a:.6e}")
    print(f"Δf / δa                         = {(f1 - f0) / da:.10f}  (в точной арифметике ровно 1)")
    print(f"относит. изменение входа δa/a   = {rel_in:.6e}")
    print(f"предсказание: cond · δa/a        = {rel_out_pred:.6e}")
    print(f"факт: |Δf| / |f|                 = {rel_out_fact:.6e}")
    print("""
Вывод: совпадает — входные данные изменились всего на 1e-9 (относительно), а
результат на 10%, ровно в cond ≈ 1e8 раз больше. Δf/δa ≈ 1 отличается от 1 в 8-м
знаке: само число 1 + 1e-8 в float хранится с ошибкой ~1e-16, и после вычитания
эта крошечная ошибка тоже усилилась в 1e8 раз. Виноват не алгоритм, а задача.""")


# #####################################################################
# ЗАДАЧА 3. Кратные корни — плохая обусловленность
# Условие: x^2 - 2x + (1 - eps) = 0, eps = 1e-2, 1e-4, 1e-6; таблица сдвигов корня
# #####################################################################
def task3():
    header("Задача 3. Кратные корни — плохая обусловленность")
    print("x^2 - 2x + (1 - eps) = 0, точный корень без возмущения x = 1 (кратность 2)")
    rows, prev = [], None
    for eps in [1e-2, 1e-4, 1e-6]:
        a, b, c = 1.0, -2.0, 1.0 - eps
        disc = b * b - 4 * a * c
        x1 = (-b + math.sqrt(disc)) / (2 * a)
        x2 = (-b - math.sqrt(disc)) / (2 * a)
        shift = abs(x1 - 1)
        ratio = "—" if prev is None else f"{prev / shift:.2f}"
        rows.append([eps, f"{x1:.10f}", f"{x2:.10f}", fmt(shift), fmt(shift / eps), ratio])
        prev = shift
    table(["eps", "x1", "x2", "сдвиг корня", "сдвиг / eps", "отношение сдвигов"], rows)
    print("""
Сдвиг корня = sqrt(eps): eps уменьшаем в 100 раз — сдвиг уменьшается лишь в 10 раз.
Коэффициент усиления «сдвиг/eps» = 1/sqrt(eps) растёт без ограничений (10, 100, 1000),
то есть cond задачи → бесконечность.
Вывод: для корня кратности m сдвиг ~ eps^(1/m), поэтому кратные корни очень плохо
обусловлены: изменение коэффициента в 6-м знаке сдвигает двукратный корень уже в 3-м.""")


# #####################################################################
# ЗАДАЧА 4. Обусловленность vs устойчивость — различие
# Условие: свой пример: хорошо обусловленная задача + устойчивый и неустойчивый алгоритм
# #####################################################################
def task4():
    header("Задача 4. Обусловленность vs устойчивость: e^(-x) через ряд Тейлора")
    print("""Задача: вычислить f(x) = e^(-x) при x от 1 до 30.
cond = |x · f'(x)/f(x)| = x, т.е. не больше 30 — задача ХОРОШО обусловлена
(теряем максимум ~1.5 десятичных знака из 16).
  «неустойчиво»: e^(-x) = Σ (-x)^k / k!   — знакопеременный ряд
  «устойчиво»:   e^(-x) = 1 / Σ x^k / k!  — все слагаемые положительные""")

    def exp_neg_bad(x):
        s, t, k = 0.0, 1.0, 0
        while abs(t) > 1e-30 * max(abs(s), 1e-300) or k < 5:
            s += t
            k += 1
            t *= -x / k
        return s

    def exp_neg_good(x):
        s, t, k = 0.0, 1.0, 0
        while t > 1e-17 * s or k < 5:
            s += t
            k += 1
            t *= x / k
        return 1.0 / s

    xs = [1, 5, 10, 15, 20, 25, 30]
    rows, eb, eg = [], [], []
    for x in xs:
        ref = D(-x).exp()
        bad, good = exp_neg_bad(x), exp_neg_good(x)
        e1, e2 = rel_err(bad, ref), rel_err(good, ref)
        eb.append(e1); eg.append(e2)
        rows.append([x, f"{float(ref):.6e}", f"{bad:.6e}", f"{good:.6e}", fmt(e1), fmt(e2)])
    table(["x", "эталон", "ряд (плохо)", "1/ряд (хорошо)", "ошибка плохого", "ошибка хорошего"], rows)

    plt.figure(figsize=(6, 4))
    plt.semilogy(xs, eb, "o-", label="Σ(-x)^k/k!  (неустойчиво)")
    plt.semilogy(xs, eg, "s-", label="1/Σx^k/k!  (устойчиво)")
    plt.semilogy(xs, [x * 2.2e-16 for x in xs], "k--", label="cond·eps = x·eps (предел задачи)")
    plt.xlabel("x"); plt.ylabel("относительная ошибка"); plt.title("Задача 4: e^(-x)")
    plt.legend(); plt.grid(True, which="both", alpha=.3); plt.tight_layout()
    plt.savefig("task4_exp.png", dpi=120); plt.close()
    print("График: task4_exp.png")
    print("""
Проблема ЗАДАЧИ: её нет — cond = x мал, и устойчивый алгоритм даёт ошибку ~1e-16,
как и обещает обусловленность (пунктир на графике).
Проблема АЛГОРИТМА: в знакопеременном ряду слагаемые огромные (при x=20 до ~4e7),
а результат крошечный (~2e-9). Ошибки округления больших слагаемых (~1e-9) того же
размера, что и ответ, — при x >= 20 результат мусорный (ошибка в разы и на порядки).""")


