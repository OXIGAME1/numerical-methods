# ЗАДАЧА 13. Воспроизводимость эксперимента
# Условие: 1e5 случайных чисел, seed 42/43, sum / fsum / np.sum, версии Python и numpy
# #####################################################################
def task13():
    header("Задача 13. Воспроизводимость эксперимента")
    N = 10**5
    print(f"Python  : {sys.version.split()[0]}")
    print(f"numpy   : {np.__version__}")
    print(f"N       : {N}")

    def experiment(seed):
        random.seed(seed)
        data = {
            "random": [random.random() for _ in range(N)],
            "numpy rng": np.random.default_rng(seed).random(N).tolist(),
        }
        res = {}
        for src, lst in data.items():
            naive = 0.0
            for v in lst:                  # наивный цикл — для сравнения
                naive += v
            res[src] = {
                "sum": sum(lst),
                "fsum": math.fsum(lst),    # корректно округлённая (точная) сумма
                "np.sum": float(np.sum(np.array(lst))),
                "цикл": naive,
            }
        return res

    r1, r2 = experiment(42), experiment(42)
    same = r1 == r2
    print(f"\nДва запуска с seed=42 совпали побитово: {same}")

    print("\nОтличие от fsum в единицах последнего знака (ulp); 0 = совпало до бита:")
    rows = []
    for seed in [42, 43, 44, 45, 46]:
        r = r1 if seed == 42 else experiment(seed)
        for src in ("random", "numpy rng"):
            f = r[src]["fsum"]
            u = math.ulp(f)
            d = lambda m: f"{(r[src][m] - f) / u:+.0f}"
            rows.append([seed, src, f"{f:.10f}", d("sum"), d("np.sum"), d("цикл")])
    table(["seed", "генератор", "fsum", "sum", "np.sum", "наивный цикл"], rows)
    print("""
Результат: с одним и тем же seed все данные и все суммы совпадают побитово —
эксперимент воспроизводим. При seed=43 (и 44–46) числа другие, но картина
одинаковая: sum (в Python >= 3.12 компенсированный), np.sum (попарное суммирование)
и fsum совпадают до бита, а наивный цикл всегда отличается (на единицы–десятки ulp).
Разница между способами — свойство алгоритмов (систематическая), а не случайность;
от seed зависит только конкретное число и знак ошибки.
Вывод: без фиксации seed каждый запуск даёт другие данные и другие цифры, их нельзя
проверить и сравнить. Без версий тоже нельзя: например, sum() до Python 3.12 был
наивным и дал бы такую же ошибку, как цикл, а numpy может менять генераторы и
алгоритмы суммирования. Поэтому в отчёте всегда указываем seed и версии.""")


