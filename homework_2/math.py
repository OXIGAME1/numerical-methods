# #####################################################################
# ЗАДАЧА 3. float32 vs float64 — реальная точность
# Условие: ошибка представления 0.1 в float32 и float64
# #####################################################################
def task3():
    header("Задача 3. float32 vs float64 — реальная точность")
    err32 = float(np.float32(0.1)) - 0.1
    err64 = float(np.float64(0.1)) - 0.1
    print("ошибка float32: repr =", repr(err32), "  :.20e =", f"{err32:.20e}")
    print("ошибка float64: repr =", repr(err64), "  :.20e =", f"{err64:.20e}")

    # float64(0.1) и python-float 0.1 — одно и то же число, поэтому ошибка = 0.
    # Для честного сравнения посчитаем ошибку относительно ТОЧНОГО 0.1 (дробь 1/10).
    from fractions import Fraction
    true_err32 = abs(Fraction(float(np.float32(0.1))) - Fraction(1, 10))
    true_err64 = abs(Fraction(float(np.float64(0.1))) - Fraction(1, 10))
    print("\nНастоящая ошибка float32 относительно 1/10:", f"{float(true_err32):.3e}")
    print("Настоящая ошибка float64 относительно 1/10:", f"{float(true_err64):.3e}")
    print("Во сколько раз ошибка float32 больше:", f"{float(true_err32 / true_err64):.3e}")
    print("Машинный эпсилон: float32 =", np.finfo(np.float32).eps,
          " float64 =", np.finfo(np.float64).eps)
    print("""
Пояснение: при прямом вычитании ошибка float64 получается ровно 0, потому что
обычный float в Python — это и есть float64 (ошибку вычитаем саму из себя).
Поэтому сравниваем с точной дробью 1/10: float32 ошибается примерно в 10^8 раз
сильнее (≈7 верных цифр против ≈16).
Вывод: float32 подходит, где важна скорость/память, а не точность — нейросети,
графика, грубые оценки. float64 нужен там, где ошибки накапливаются: длинные
суммы, итерационные методы, решение плохо обусловленных систем, вычитание
близких чисел, численное дифференцирование.""")


