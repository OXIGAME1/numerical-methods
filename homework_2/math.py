# ЗАДАЧА 11. keepdims и broadcasting
# Условие: центрирование и нормировка строк с keepdims
# #####################################################################
def task11():
    header("Задача 11. keepdims и broadcasting")
    X = np.random.default_rng(42).normal(size=(5, 3))
    m0 = X.mean(axis=0)
    m0k = X.mean(axis=0, keepdims=True)
    print("X.mean(axis=0).shape               =", m0.shape)
    print("X.mean(axis=0, keepdims=True).shape =", m0k.shape)
    print("(X - m0).shape  =", (X - m0).shape)
    print("(X - m0k).shape =", (X - m0k).shape)

    print("\nX.std(axis=1).shape               =", X.std(axis=1).shape)
    print("X.std(axis=1, keepdims=True).shape =", X.std(axis=1, keepdims=True).shape)
    try:
        X - X.mean(axis=1)
    except ValueError as e:
        print("X - X.mean(axis=1) БЕЗ keepdims -> ошибка:", e)

    Z = (X - X.mean(axis=1, keepdims=True)) / X.std(axis=1, keepdims=True)
    print("\nСредние по строкам после нормировки:", np.round(Z.mean(axis=1), 10))
    print("std по строкам после нормировки:    ", np.round(Z.std(axis=1), 10))
    print("""
Вывод: keepdims оставляет «свёрнутую» ось длиной 1, а не выбрасывает её.
Для axis=0 это не важно: (3,) и так растягивается на (5,3). Но для axis=1
получается (5,), а NumPy выравнивает формы СПРАВА, и (5,) пытается встать
напротив 3 столбцов -> ошибка. С keepdims получаем (5,1) — столбец, который
корректно растягивается на каждую строку.""")


