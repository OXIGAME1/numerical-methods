# ЗАДАЧА 13. Булева маска и fancy indexing
# Условие: a[a > 0], маски с &, a[[0,5,10,15]], выбросы
# #####################################################################
def task13():
    header("Задача 13. Булева маска и fancy indexing")
    a = np.random.default_rng(0).normal(size=20)
    print("a =", np.round(a, 3))

    pos = a[a > 0]
    print("\na[a > 0]: элементов =", pos.size)
    mid = a[(a > -1) & (a < 1)]
    print("a[(a > -1) & (a < 1)]: элементов =", mid.size)
    print("a[[0, 5, 10, 15]] =", np.round(a[[0, 5, 10, 15]], 3),
          " -> выборка по списку индексов: каждый 5-й элемент (fancy indexing)")
    print("a[np.abs(a) > 2] (выбросы) =", np.round(a[np.abs(a) > 2], 3))

    a[a < 0] = 0
    print("\nПосле a[a < 0] = 0:\n", np.round(a, 3))

    try:
        a[a > 0] & (a < 1)
    except TypeError as e:
        print("\na[a > 0] & (a < 1) -> ошибка:", e)
    print("""
Вывод: в Python оператор & «сильнее» сравнений, поэтому без скобок
0 & (a < 1) считается раньше сравнения и всё ломается. А в записи
a[a > 0] & (a < 1) мы вообще делаем & между числами float (выборкой) и
маской True/False — для float побитовое «И» не определено -> TypeError.
Правильно: каждое условие в скобки, (a > 0) & (a < 1), и только потом
эту общую маску — в квадратные скобки. Для масок используем & | ~,
а не and / or / not.""")


