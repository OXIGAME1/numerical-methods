# #####################################################################
# ЗАДАЧА 9. Поэлементно vs матричное
# Условие: A @ B, A.T @ B.T, A * A, почему A * B — ошибка
# #####################################################################
def task9():
    header("Задача 9. Поэлементно vs матричное")
    A = np.arange(6).reshape(2, 3)
    B = np.arange(6).reshape(3, 2)
    print("A =\n", A, "\nB =\n", B)
    print("\nA @ B, shape", (A @ B).shape, "\n", A @ B)
    print("A.T @ B.T, shape", (A.T @ B.T).shape, "\n", A.T @ B.T)
    print("A * A, shape", (A * A).shape, "\n", A * A)

    try:
        A * B
    except ValueError as e:
        print("\nA * B -> ошибка:", e)

    D = np.diag([2, 3])
    E = np.diag([4, 5])
    print("\nДиагональные D =\n", D, "\nE =\n", E)
    print("D * E =\n", D * E, "\nD @ E =\n", D @ E)
    print("Совпадают:", np.array_equal(D * E, D @ E))
    print("""
Вывод: * — поэлементное умножение, формы должны совпадать (или
«растягиваться» по правилам broadcasting). (2,3) и (3,2) не совпадают, и
растянуть их нельзя -> ошибка. @ — матричное умножение «строка на столбец»,
там нужно, чтобы число столбцов A = числу строк B: (2,3)@(3,2) -> (2,2).
У диагональных матриц вне диагонали нули, поэтому оба способа дают одно и то же.""")


